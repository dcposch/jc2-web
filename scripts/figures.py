# 3. H(x, y) = (x, xy): the input escapes while the output converges.
# --------------------------------------------------------------------------
def fig_escape():
    h = 300
    out = []
    left = Frame((-0.35, 3.4), (-0.6, 6.4), (56, 58, 215, 200))
    right = Frame((-0.35, 3.4), (-0.6, 2.4), (372, 58, 215, 200))

    out += heading(56, 'input', 'the path (1/t, t) runs off to infinity')
    out += heading(372, 'output', 'its image settles on a finite point')

    for fr, ymax in ((left, 6.4), (right, 2.4)):
        out.append(f'<path class="axis" d="{fr.path([(-0.35, 0), (3.4, 0)])}"/>')
        out.append(f'<path class="axis" d="{fr.path([(0, -0.6), (0, ymax)])}"/>')

    # Input path: x = 1/t, y = t, for t in [0.32, 6.2].
    pts = [(1 / t, t) for t in lin(0.32, 6.2, 260)]
    pts = [(x, y) for x, y in pts if x <= 3.4 and y <= 6.4]
    out.append(f'<path class="curve" d="{left.path(pts)}"/>')
    for t in (0.9, 1.6, 2.8, 5.0):
        u, v = left(1 / t, t)
        out.append(f'<circle class="dot" cx="{u:.2f}" cy="{v:.2f}" r="3.1"/>')
    out.append(f'<text class="math lbl-mark" x="{left(0.55, 4.6)[0]:.1f}" y="{left(0.55, 4.6)[1]:.1f}">xy = 1</text>')

    # Output path: the horizontal segment v = 1, marching toward (0, 1).
    out.append(f'<path class="curve" d="{right.path([(1 / 0.32, 1), (1 / 6.2, 1)])}"/>')
    for t in (0.9, 1.6, 2.8, 5.0):
        u, v = right(min(1 / t, 3.4), 1)
        out.append(f'<circle class="dot" cx="{u:.2f}" cy="{v:.2f}" r="3.1"/>')
    au, av = right(0, 1)
    out.append(f'<circle class="open" cx="{au:.2f}" cy="{av:.2f}" r="4.6"/>')
    out.append(f'<text class="lbl-mark" x="{au + 9:.1f}" y="{av - 18:.1f}">asymptotic value (0, 1)</text>')

    out.append('<path class="arrow" d="M292 158 L352 158"/>')
    out.append('<path class="arrowhead" d="M352 158 l-6 -3.4 v6.8 Z"/>')
    out.append('<text class="lbl-mark math" x="310" y="150">H</text>')
    out.append(footnote(56, h, 'not a Keller map: the Jacobian of H is x, which vanishes along a line'))

    write(
        "escape-to-infinity",
        "The path (1/t, t) escaping to infinity while its image under H(x,y)=(x,xy) converges to (0,1).",
        svg(W, h, "\n".join(out)),
    )


