#!/usr/bin/env python3
"""Generate the static SVG figures for jc2.fun.

Every curve here is computed from the map or equation it illustrates, so the
pictures can be regenerated and checked rather than trusted.  Output goes to
src/components/figures/*.astro.  Run:  python3 scripts/figures.py
"""
from __future__ import annotations

import math
import pathlib

OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "figures"
W = 640  # text-measure figures
WIDE = 880


class Frame:
    """Maps mathematical coordinates into a rectangle of the SVG canvas."""

    def __init__(self, xr, yr, box):
        (self.x0, self.x1), (self.y0, self.y1) = xr, yr
        self.px, self.py, self.pw, self.ph = box

    def __call__(self, x, y):
        u = self.px + (x - self.x0) / (self.x1 - self.x0) * self.pw
        v = self.py + self.ph - (y - self.y0) / (self.y1 - self.y0) * self.ph
        return u, v

    def path(self, pts, close=False):
        d = []
        for i, (x, y) in enumerate(pts):
            u, v = self(x, y)
            d.append(f"{'M' if i == 0 else 'L'}{u:.2f} {v:.2f}")
        if close:
            d.append("Z")
        return "".join(d)


def lin(a, b, n=160):
    return [a + (b - a) * i / (n - 1) for i in range(n)]


def svg(width, height, body, extra=""):
    return (
        f'<svg viewBox="0 0 {width} {height}" xmlns="http://www.w3.org/2000/svg" '
        f'aria-hidden="true" focusable="false"{extra}>\n{body}\n</svg>'
    )


# Rough advance widths, in px per character, for the fonts the figures use.
_ADVANCE = {"": 6.3, "ttl": 8.4, "math": 6.6}


def lint(name, markup, width):
    """Warn when a generated label would be clipped or would overlap a panel."""
    import re as _re

    problems = []
    for m in _re.finditer(r'<text class="([^"]*)" x="([\d.]+)" y="([\d.]+)">([^<]*)</text>'
                          r'|<text x="([\d.]+)" y="([\d.]+)" class="([^"]*)">([^<]*)</text>', markup):
        if m.group(4) is not None:
            cls, x, y, text = m.group(1), float(m.group(2)), float(m.group(3)), m.group(4)
        else:
            cls, x, y, text = m.group(7), float(m.group(5)), float(m.group(6)), m.group(8)
        kind = "ttl" if "ttl" in cls else ("math" if "math" in cls else "")
        end = x + len(text) * _ADVANCE[kind]
        if end > width - 4:
            problems.append(f"    overruns canvas by {end - width:.0f}px: {text!r}")
        elif y < 60 and x < 340 and end > 366 and width == W:
            # Only the heading band has a right-hand neighbour; full-width
            # footer lines below the panels are fine.
            problems.append(f"    runs into the right panel's heading: {text!r}")
    for p in problems:
        print(f"  ! {name}:\n{p}")
    return not problems


def write(name, description, markup):
    """Emit a bare SVG, inlined into the prose by src/lib/remark-figure.mjs."""
    OUT.mkdir(parents=True, exist_ok=True)
    header = f"<!-- Generated by scripts/figures.py. {description} -->\n"
    width = W if f'viewBox="0 0 {W} ' in markup else WIDE
    ok = lint(name, markup, width)
    (OUT / f"{name}.svg").write_text(header + markup + "\n")
    print(f"  wrote {name}.svg{'' if ok else '  (see warnings above)'}")


