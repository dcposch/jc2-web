# 5. The Newton polygon of y^2 - x^3 - x, and the curve it predicts.
# --------------------------------------------------------------------------
def fig_newton():
    h = 336
    out = []
    left = Frame((-0.55, 3.6), (-0.55, 2.6), (96, 66, 285, 190))
    right = Frame((-1.4, 3.1), (-6.0, 6.0), (510, 66, 285, 190))

    out += heading(96, 'exponents', 'the monomials of y² − x³ − x, and their hull')
    out += heading(510, 'the curve', 'a real slice of y² = x³ + x, against y = ±x^{3/2}')

    # Lattice.
    for i in range(4):
        for j in range(3):
            u, v = left(i, j)
            out.append(f'<circle class="lattice" cx="{u:.2f}" cy="{v:.2f}" r="1.4"/>')
    out.append(f'<path class="axis" d="{left.path([(-0.4, 0), (3.5, 0)])}"/>')
    out.append(f'<path class="axis" d="{left.path([(0, -0.4), (0, 2.5)])}"/>')
    out.append(f'<text class="math lbl-ink" x="{left(3.4, 0)[0]:.1f}" y="{left(0, 0)[1] + 20:.1f}">i</text>')
    out.append(f'<text class="math lbl-ink" x="{left(0, 0)[0] - 18:.1f}" y="{left(0, 2.4)[1]:.1f}">j</text>')

    # Hull of {(0,2), (3,0), (1,0)}.
    hull = [(0, 2), (3, 0), (1, 0)]
    out.append(f'<path class="hull" d="{left.path(hull, close=True)}"/>')
    # The edge that sets the balance 2r = 3.
    out.append(f'<path class="edge" d="{left.path([(0, 2), (3, 0)])}"/>')
    for (i, j), lbl in (((0, 2), "y²"), ((3, 0), "x³"), ((1, 0), "x")):
        u, v = left(i, j)
        out.append(f'<circle class="dot" cx="{u:.2f}" cy="{v:.2f}" r="4.2"/>')
        out.append(f'<text class="math lbl-ink" x="{u + 9:.1f}" y="{v - 8:.1f}">{lbl}</text>')
    mu, mv = left(1.5, 1.0)
    out.append(f'<text class="lbl-mark" x="{mu + 12:.1f}" y="{mv - 4:.1f}">slope −⅔ → r = 3/2</text>')

    # The curve y^2 = x^3 + x, real slice, and its leading approximation.
    upper = [(x, math.sqrt(x ** 3 + x)) for x in lin(0, 3.05, 300)]
    out.append(f'<path class="curve-heavy" d="{right.path(upper)}"/>')
    out.append(f'<path class="curve-heavy" d="{right.path([(x, -y) for x, y in upper])}"/>')
    approx = [(x, x ** 1.5) for x in lin(0, 3.05, 300)]
    out.append(f'<path class="dashed" d="{right.path(approx)}"/>')
    out.append(f'<path class="dashed" d="{right.path([(x, -y) for x, y in approx])}"/>')
    out.append(f'<path class="axis" d="{right.path([(-1.3, 0), (3.05, 0)])}"/>')
    out.append(f'<path class="axis" d="{right.path([(0, -5.8), (0, 5.8)])}"/>')
    out.append(f'<text class="math lbl-ink" x="{right(2.05, 4.45)[0]:.1f}" y="{right(2.05, 4.45)[1]:.1f}">y² = x³ + x</text>')
    out.append(f'<text class="lbl-mark math" x="{right(1.55, -4.3)[0]:.1f}" y="{right(1.55, -4.3)[1]:.1f}">y = ±x^(3/2)</text>')
    out.append(footnote(510, h, 'the two agree to leading order and separate below it'))

    write(
        "newton-polygon",
        "The Newton polygon of y^2 - x^3 - x beside the real slice of the curve and its leading approximation.",
        svg(WIDE, h, "\n".join(out), extra=' preserveAspectRatio="xMidYMid meet"'),
    )


