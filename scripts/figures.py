# 1. A shear: (x, y) -> (x + y^2, y).  Nonlinear, yet undone exactly.
# --------------------------------------------------------------------------
def fig_shear():
    h = 300
    xr, yr = (-2.2, 4.6), (-1.7, 1.7)
    pw, ph = 285, 200
    left = Frame(xr, yr, (14, 58, pw, ph))
    right = Frame(xr, yr, (341, 58, pw, ph))
    out = []

    def panel(fr, sheared, title, sub):
        g = [f'<text class="lbl-ink ttl" x="{fr.px}" y="30">{title}</text>',
             f'<text x="{fr.px}" y="46">{sub}</text>']
        # Axes.
        g.append(f'<path class="axis" d="{fr.path([(xr[0], 0), (xr[1], 0)])}"/>')
        g.append(f'<path class="axis" d="{fr.path([(0, yr[0]), (0, yr[1])])}"/>')

        def img(x, y):
            return (x + y * y, y) if sheared else (x, y)

        # Vertical lines x = c become the parabolas x = c + y^2.
        c = -2.0
        while c <= 2.001:
            pts = [img(c, t) for t in lin(-1.5, 1.5)]
            pts = [p for p in pts if xr[0] <= p[0] <= xr[1]]
            if len(pts) > 1:
                g.append(f'<path class="grid" d="{fr.path(pts)}"/>')
            c += 0.5
        # Horizontal lines y = c slide sideways but stay straight.
        c = -1.5
        while c <= 1.501:
            pts = [img(t, c) for t in lin(-2.0, 2.0, 60)]
            pts = [p for p in pts if xr[0] <= p[0] <= xr[1]]
            if len(pts) > 1:
                g.append(f'<path class="grid" d="{fr.path(pts)}"/>')
            c += 0.5
        # Two tracked points.
        for (x, y), lbl in (((-1.0, 1.0), "a"), ((1.0, -1.5), "b")):
            u, v = fr(*img(x, y))
            g.append(f'<circle class="dot" cx="{u:.2f}" cy="{v:.2f}" r="3.6"/>')
            g.append(f'<text class="lbl-mark math" x="{u + 7:.2f}" y="{v - 6:.2f}">{lbl}</text>')
        return "\n".join(g)

    out.append(panel(left, False, "before", "the plane, ruled by a unit grid"))
    out.append(panel(right, True, "after", "the image under (x, y) ↦ (x + y², y)"))
    # Arrow between the panels.
    out.append('<path class="arrow" d="M308 158 L332 158"/>')
    out.append('<path class="arrowhead" d="M332 158 l-6 -3.4 v6.8 Z"/>')
    out.append('<text class="lbl-mark" x="303" y="148">F</text>')
    write(
        "shear-grid",
        "A unit grid and its image under the shear (x, y) -> (x + y^2, y).",
        svg(W, h, "\n".join(out)),
    )


# --------------------------------------------------------------------------
# 2. E(s,t) = (e^s cos t, e^s sin t): locally reversible, globally many-to-one.
# --------------------------------------------------------------------------
def fig_wrap():
    h = 312
    out = []
    # Exactly three whole strips, so every band is the same height.
    T0, T1 = -math.pi, 5 * math.pi
    left = Frame((-2.4, 2.4), (T0, T1), (56, 62, 210, 206))
    right = Frame((-2.9, 2.9), (-2.9, 2.9), (372, 62, 210, 206))

    out.append('<text class="lbl-ink ttl" x="56" y="32">domain</text>')
    out.append('<text x="56" y="48">(s, t), in strips of height 2π</text>')
    out.append('<text class="lbl-ink ttl" x="372" y="32">image</text>')
    out.append('<text x="372" y="48">the punctured plane</text>')

    for k, base in enumerate((-math.pi, math.pi, 3 * math.pi)):
        top = base + 2 * math.pi
        pts = [(-2.4, base), (2.4, base), (2.4, top), (-2.4, top)]
        out.append(f'<path class="{"strip-a" if k % 2 == 0 else "strip-b"}" d="{left.path(pts, close=True)}"/>')
        u, v = left(-2.2, (base + top) / 2)
        out.append(f'<text x="{u:.1f}" y="{v:.1f}" class="lbl-faint">k={k}</text>')

    out.append(f'<path class="axis" d="{left.path([(-2.4, 0), (2.4, 0)])}"/>')
    out.append(f'<path class="axis" d="{left.path([(0, T0), (0, T1)])}"/>')
    out.append(f'<text class="math lbl-ink" x="{left(2.02, 0)[0]:.1f}" y="{left(0, 0)[1] - 7:.1f}">s</text>')
    out.append(f'<text class="math lbl-ink" x="{left(0, 0)[0] + 7:.1f}" y="{left(0, T1 - 0.7)[1]:.1f}">t</text>')

    for r in (0.6, 1.2, 1.9, 2.6):
        pts = [(r * math.cos(a), r * math.sin(a)) for a in lin(0, 2 * math.pi)]
        out.append(f'<path class="grid" d="{right.path(pts, close=True)}"/>')
    for k in range(12):
        a = k * math.pi / 6
        out.append(f'<path class="grid" d="{right.path([(0.25*math.cos(a), 0.25*math.sin(a)), (2.75*math.cos(a), 2.75*math.sin(a))])}"/>')
    ou, ov = right(0, 0)
    out.append(f'<circle class="puncture" cx="{ou:.2f}" cy="{ov:.2f}" r="4"/>')
    out.append(f'<text class="lbl-faint" x="{right(-2.75, -2.55)[0]:.1f}" y="{right(0, -2.55)[1]:.1f}">origin omitted</text>')

    # One patch, drawn twice in the domain a full strip apart, once in the image.
    s0, ds, t0, dt = 0.35, 0.22, 1.15, 0.45
    for t in (t0, t0 + 2 * math.pi):
        pts = [(s0 - ds, t - dt), (s0 + ds, t - dt), (s0 + ds, t + dt), (s0 - ds, t + dt)]
        out.append(f'<path class="patch" d="{left.path(pts, close=True)}"/>')
    ring = []
    for i, sv in enumerate((s0 - ds, s0 + ds)):
        arc = [(math.exp(sv) * math.cos(t), math.exp(sv) * math.sin(t)) for t in lin(t0 - dt, t0 + dt, 28)]
        ring += arc if i == 0 else arc[::-1]
    out.append(f'<path class="patch" d="{right.path(ring, close=True)}"/>')

    out.append('<path class="arrow" d="M292 168 L346 168"/>')
    out.append('<path class="arrowhead" d="M346 168 l-6 -3.4 v6.8 Z"/>')
    out.append('<text class="lbl-mark math" x="310" y="160">E</text>')
    out.append(f'<text class="lbl-mark" x="56" y="{h - 12}">the two marked patches lie 2π apart and share one image</text>')

    write(
        "exponential-wrap",
        "Strips of height 2pi in the (s,t) plane wrapping onto the punctured plane under E.",
        svg(W, h, "\n".join(out)),
    )


